"""Score arms with the unchanged audit.py (Qwen3Guard-4B + 0.6B via AuditKIT) on a private Kaggle kernel (T4 x2).

    python scripts/kaggle_score.py push   E0 pgp_val     # stage inputs as a private dataset, push + run the kernel
    python scripts/kaggle_score.py status
    python scripts/kaggle_score.py output E0 pgp_val     # -> runs/<arm>/colab/{judged.jsonl,auditkit.json}
    JUDGE_BATCH=1 python scripts/kaggle_score.py push pgp_val   # long inputs (validation set): batch 4 OOMs a T4

The Qwen3Guard judges are ungated, so no secret is needed and the kernel can be started from the CLI (unlike the
CircuitKIT job, scripts/kaggle_job.py). Settings match scripts/colab_score.sh exactly (bf16, JUDGE_BATCH=4, --no-lid;
language ID is added locally by scripts/finalize_arm.sh), so arms stay comparable. Up to two arms run in parallel,
one per GPU. Outputs land in runs/<arm>/colab/ so finalize_arm.sh works unchanged.
"""

import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = str(ROOT / ".venv/bin/kaggle")
USER = os.environ.get("KAGGLE_USERNAME") or sys.exit("set KAGGLE_USERNAME")
DATASET, KERNEL = "refusal-parity-score-inputs", "refusal-parity-score"
STAGE = ROOT / "kaggle_job"

SCRIPT = """# Auto-generated by scripts/kaggle_score.py. Do not edit here.
import os, shutil, subprocess, sys, time
from pathlib import Path
ARMS = {arms!r}
BATCH = {batch!r}
# The mount path differs across Kaggle images (/kaggle/input/<slug> vs nested), so locate the inputs by content
INP = next(Path("/kaggle/input").rglob("audit.py")).parent
missing = [a for a in ARMS if not (INP / f"{{a}}.responses.jsonl").exists()]
assert not missing, f"inputs missing under {{INP}}: {{missing}}"
print("inputs at", INP, flush=True)
W = Path("/kaggle/working")
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "auditkit[transformers]==1.1.3", "safetune==0.1.10", "transformers==5.20.2"], check=True)
(W / "src").mkdir(exist_ok=True)
for f in INP.glob("*.py"):
    shutil.copy(f, W / "src" / f.name)
procs = []
for i, arm in enumerate(ARMS):
    (W / "runs" / arm).mkdir(parents=True, exist_ok=True)
    shutil.copy(INP / f"{{arm}}.responses.jsonl", W / "runs" / arm / "responses.jsonl")
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(i % 2), JUDGE_BATCH=BATCH,
               PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True")
    log = open(W / f"{{arm}}.score.log", "w")
    procs.append((arm, subprocess.Popen([sys.executable, "-u", "audit.py", "score", f"../runs/{{arm}}/responses.jsonl",
                                         "--no-lid"], cwd=W / "src", env=env, stdout=log, stderr=subprocess.STDOUT)))
    if i % 2 == 1:  # two GPUs: wait for this pair before starting the next
        for a, p in procs[-2:]:
            p.wait()
for arm, p in procs:
    p.wait()
    print(arm, "exit", p.returncode, flush=True)
    print(open(W / f"{{arm}}.score.log").read()[-1500:], flush=True)
"""


def kaggle(*args, check=True):
    return subprocess.run([KAGGLE, *args], check=check, capture_output=True, text=True)


def push(arms):
    ds = STAGE / DATASET
    shutil.rmtree(ds, ignore_errors=True)
    ds.mkdir(parents=True)
    for f in (ROOT / "src").glob("*.py"):
        shutil.copy(f, ds / f.name)
    for arm in arms:
        shutil.copy(ROOT / "runs" / arm / "responses.jsonl", ds / f"{arm}.responses.jsonl")
    (ds / "dataset-metadata.json").write_text(
        json.dumps(dict(title=DATASET, id=f"{USER}/{DATASET}", licenses=[dict(name="other")]))
    )
    exists = kaggle("datasets", "status", f"{USER}/{DATASET}", check=False).returncode == 0
    r = (
        kaggle("datasets", "version", "-p", str(ds), "-m", f"inputs for {' '.join(arms)}")
        if exists
        else kaggle("datasets", "create", "-p", str(ds))
    )  # private by default
    print(r.stdout.strip()[-300:])
    for _ in range(40):  # the kernel must not start before the new dataset version is ready
        st = kaggle("datasets", "status", f"{USER}/{DATASET}", check=False).stdout.strip()
        if "ready" in st:
            break
        time.sleep(15)
    print("dataset status:", st)
    kd = STAGE / KERNEL
    kd.mkdir(parents=True, exist_ok=True)
    (kd / "script.py").write_text(SCRIPT.format(arms=list(arms), batch=os.environ.get("JUDGE_BATCH", "4")))
    (kd / "kernel-metadata.json").write_text(
        json.dumps(
            dict(
                id=f"{USER}/{KERNEL}",
                title=KERNEL,
                code_file="script.py",
                language="python",
                kernel_type="script",
                is_private=True,
                enable_gpu=True,
                enable_internet=True,
                machine_shape="NvidiaTeslaT4",
                dataset_sources=[f"{USER}/{DATASET}"],
                competition_sources=[],
                kernel_sources=[],
                model_sources=[],
            ),
            indent=1,
        )
    )
    print(kaggle("kernels", "push", "-p", str(kd)).stdout.strip())


def output(arms):
    tmp = STAGE / "score-output"
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    kaggle("kernels", "output", f"{USER}/{KERNEL}", "-p", str(tmp))
    for arm in arms:
        dst = ROOT / "runs" / arm / "colab"  # same place colab_score.sh writes, so finalize_arm.sh is unchanged
        dst.mkdir(parents=True, exist_ok=True)
        for f in ("judged.jsonl", "auditkit.json"):
            src = tmp / "runs" / arm / f
            if src.exists():
                shutil.copy(src, dst / f)
        print(arm, sorted(p.name for p in dst.iterdir()))


if __name__ == "__main__":
    action, arms = sys.argv[1], sys.argv[2:]
    if action == "push":
        push(arms)
    elif action == "status":
        print(kaggle("kernels", "status", f"{USER}/{KERNEL}").stdout.strip())
    elif action == "output":
        output(arms)
