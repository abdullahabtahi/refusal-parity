"""Run a colab_circuit.py mode as a private Kaggle kernel (GPU T4 x2, ~29 GB RAM) with the official kaggle CLI.

    python scripts/kaggle_job.py push   all      scratch_colab/circuit_spec.json     [--no-run]
    python scripts/kaggle_job.py status all
    python scripts/kaggle_job.py output all               # -> runs/circuitkit/kaggle_<mode>/

The HF token comes from Kaggle Secrets (secret name HF_TOKEN, attached to the notebook once in the Kaggle UI):
the kernel metadata cannot attach secrets, and the token must never sit in code, data or logs. A CLI-started run
cannot read user secrets (get_secret -> HTTP 400), so push with --no-run and start it in the UI: Save Version ->
Save & Run All; then poll status and fetch output from the CLI.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = str(ROOT / ".venv/bin/kaggle")
USER = os.environ.get("KAGGLE_USERNAME") or sys.exit("set KAGGLE_USERNAME")

HEADER = """# Auto-generated by scripts/kaggle_job.py from src/colab_circuit.py. Do not edit here.
import os, subprocess, sys
os.environ["PYTORCH_CUDA_ALLOC_CONF"] = "expandable_segments:True"  # before torch loads; T4 headroom is tight
from kaggle_secrets import UserSecretsClient
os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")  # Kaggle secret store; never printed
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "circuitkit==0.2.0", "transformer-lens==3.8.0"], check=True)
os.chdir("/kaggle/working")
"""


def slug(mode):
    """Every mode runs as a new version of one kernel: the HF_TOKEN secret is attached per kernel in the UI."""
    return "refusal-parity-circuitkit-parity"


def push(mode, spec_path, no_run):
    src = (ROOT / "src/colab_circuit.py").read_text()
    body = src.split('\nif __name__ == "__main__":')[0]  # the job functions, without the CLI entry point
    spec = json.loads(Path(spec_path).read_text())
    script = (
        HEADER + body + f"\n\nSPEC = json.loads({json.dumps(json.dumps(spec, ensure_ascii=False))})\n"
        f"JOBS[{mode!r}](SPEC)\n"
    )
    d = ROOT / "kaggle_job" / slug(mode)
    d.mkdir(parents=True, exist_ok=True)
    (d / "script.py").write_text(script)
    (d / "kernel-metadata.json").write_text(
        json.dumps(
            dict(
                id=f"{USER}/{slug(mode)}",
                title=slug(mode),
                code_file="script.py",
                language="python",
                kernel_type="script",
                is_private=True,
                enable_gpu=True,
                enable_internet=True,
                machine_shape="NvidiaTeslaT4",
                dataset_sources=[],
                competition_sources=[],
                kernel_sources=[],
                model_sources=[],
            ),
            indent=1,
        )
    )
    cmd = [KAGGLE, "kernels", "push", "-p", str(d)] + (["--no-run"] if no_run else [])
    subprocess.run(cmd, check=True)


if __name__ == "__main__":
    action, mode = sys.argv[1], sys.argv[2]
    if action == "push":
        push(mode, sys.argv[3], "--no-run" in sys.argv)
    elif action == "status":
        subprocess.run([KAGGLE, "kernels", "status", f"{USER}/{slug(mode)}"], check=True)
    elif action == "output":
        out = ROOT / "runs/circuitkit" / f"kaggle_{mode}"
        out.mkdir(parents=True, exist_ok=True)
        subprocess.run([KAGGLE, "kernels", "output", f"{USER}/{slug(mode)}", "-p", str(out)], check=True)
