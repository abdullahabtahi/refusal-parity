"""Shared state for paper_numbers: the macro writer, number formats and cached result loaders."""

import functools
import json

from refusal_parity.analysis import analyze
from refusal_parity.common import LANGS, ROOT, RUNS

OUT = ROOT / "paper" / "numbers.tex"
lines = ["% AUTO-GENERATED by src/refusal_parity/reporting/paper_numbers — do not edit by hand.", ""]


def macro(name, value, source, fmt="{:.2f}"):
    v = value if isinstance(value, str) else (fmt(value) if callable(fmt) else fmt.format(value))
    lines.append(f"\\newcommand{{\\{name}}}{{{v}}}  % {source}")


pct = "{:.0f}\\%".format
pct1 = "{:.1f}\\%".format
spp1 = lambda v: f"{round(100 * v, 1) + 0.0:+.1f}"  # signed percentage points; never "-0.0"


# --- shared evidence (loaded once) ---------------------------------------------------------------------------------
@functools.cache
def arms_pairs():
    return json.loads((RUNS / "arms_report.json").read_text())["pairs"]


def pair(a, b, j="q3g4b"):
    return next(r for r in arms_pairs() if r["a"] == a and r["b"] == b and r["judge"] == j)


@functools.cache
def controls():
    return json.loads((RUNS / "controls_report.json").read_text())


@functools.cache
def closed_model_harm():
    """Per-language harmful-answer rate of Gemini 3.5 Flash-Lite under the Gemini judge (ten study languages)."""
    gem = analyze.load("GEM-lite", judge="gem")
    return gem[(gem.kind == "harmful") & gem.lang.isin(LANGS)].groupby("lang").unsafe.mean()


@functools.cache
def per_lang(run, judge="q3g4b"):
    return analyze.summary(analyze.load(run, judge=judge))[0].set_index("lang")


pp = lambda v: f"{abs(100 * v):.1f}"  # magnitude; the sign is carried by the prose
cell = lambda v: r"${:+.1f}$ {{\scriptsize[${:+.1f}$, ${:+.1f}$]}}".format(*(100 * x for x in v))


def triple(name, est, src, signed=True):
    """name, nameLo, nameHi from a (mean, lo, hi) estimate, in percentage points."""
    f = spp1 if signed else pp
    for suffix, v in zip(("", "Lo", "Hi"), est, strict=True):
        macro(name + suffix, v, src, f)
